#!/bin/bash

echo "=================================================="
echo "   🛡️ جاري تنصيب وتجهيز بوت الحماية الذكي 🛡️   "
echo "=================================================="

# 1. تحديث حزم نظام السيرفر وتثبيت المتطلبات الأساسية
echo "🔄 جاري تحديث السيرفر وتثبيت بايثون..."
sudo apt update && sudo apt upgrade -y
sudo apt install python3 python3-pip python3-dev build-base git -y

# 2. تثبيت مكتبات بايثون المطلوبة من ملف requirements
echo "📦 جاري تثبيت مكتبات بايثون..."
pip3 install -r requirements.txt

# 3. إعداد ملف التكوين التفاعلي والآمن
echo "⚙️ إعداد بيئة الأمان والتوكن..."
read -p "🔹 أدخل توكن البوت (Bot Token) من BotFather: " BOT_TOKEN
read -p "🔹 أدخل الأيدي الخاص بك كأدمن (Admin ID): " ADMIN_ID

# كتابة البيانات داخل ملف config.json السري بالسيرفر
cat <<EOF > config.json
{
    "bot_token": "$BOT_TOKEN",
    "admin_id": "$ADMIN_ID"
}
EOF

echo "✅ تم حفظ البيانات وإعداد الملفات بنجاح!"

# 4. تشغيل البوت في الخلفية لضمان استمراره حتى بعد إغلاق النافذة
echo "🚀 جاري تشغيل البوت الآن في الخلفية..."
nohup python3 bot.py > bot.log 2>&1 &

echo "=================================================="
echo "🎉 مبروك! البوت يعمل الآن بنجاح في الخلفية 24 ساعة."
echo "تستطيع فحص السجل عبر أمر: tail -f bot.log"
echo "=================================================="
